    profesor_id BIGINT               REFERENCES profesores (id)         ON DELETE SET NULL,
    periodo_id  BIGINT      NOT NULL REFERENCES periodos_escolares (id) ON DELETE RESTRICT,
    cupo_maximo INTEGER     NOT NULL,
    turno       VARCHAR(20) NOT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_grupo_periodo_materia_clave UNIQUE (periodo_id, materia_id, clave),
    CONSTRAINT ck_grupos_cupo  CHECK (cupo_maximo > 0),
    CONSTRAINT ck_grupos_turno CHECK (turno IN ('MATUTINO', 'VESPERTINO', 'NOCTURNO'))
);
CREATE INDEX idx_grupos_periodo  ON grupos (periodo_id);
CREATE INDEX idx_grupos_materia  ON grupos (materia_id);
CREATE INDEX idx_grupos_profesor ON grupos (profesor_id);

CREATE TABLE horarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id    BIGINT      NOT NULL REFERENCES grupos (id) ON DELETE CASCADE,
    dia         VARCHAR(15) NOT NULL,
