-- KARDEX (historial académico definitivo)
-- ---------------------------------------------------------------------
CREATE TABLE kardex (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id          BIGINT       NOT NULL REFERENCES alumnos (id)            ON DELETE RESTRICT,
    materia_id         BIGINT       NOT NULL REFERENCES materias (id)           ON DELETE RESTRICT,
    periodo_id         BIGINT       NOT NULL REFERENCES periodos_escolares (id) ON DELETE RESTRICT,
    inscripcion_id     BIGINT REFERENCES inscripciones (id) ON DELETE SET NULL,
    calificacion_final NUMERIC(5,2) NOT NULL,
    creditos_obtenidos INTEGER      NOT NULL,
    estatus            VARCHAR(15)  NOT NULL,
    tipo_acreditacion  VARCHAR(20)  NOT NULL DEFAULT 'ORDINARIO',
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_kardex_alumno_materia_periodo UNIQUE (alumno_id, materia_id, periodo_id),
    CONSTRAINT uk_kardex_inscripcion UNIQUE (inscripcion_id),
    CONSTRAINT ck_kardex_calificacion CHECK (calificacion_final >= 0 AND calificacion_final <= 100),
    CONSTRAINT ck_kardex_creditos CHECK (creditos_obtenidos >= 0),
    CONSTRAINT ck_kardex_estatus CHECK (estatus IN ('APROBADA', 'REPROBADA')),
    CONSTRAINT ck_kardex_tipo CHECK (tipo_acreditacion IN ('ORDINARIO', 'EXTRAORDINARIO', 'REGULARIZACION'))
);
CREATE INDEX idx_kardex_alumno_estatus ON kardex (alumno_id, estatus);
CREATE INDEX idx_kardex_materia ON kardex (materia_id);
CREATE INDEX idx_kardex_periodo ON kardex (periodo_id);
