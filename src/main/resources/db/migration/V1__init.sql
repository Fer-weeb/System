CREATE TABLE carreras (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave              VARCHAR(20)  NOT NULL,
    nombre             VARCHAR(150) NOT NULL,
    descripcion        VARCHAR(500),
    duracion_semestres INTEGER      NOT NULL,
    creditos_totales   INTEGER      NOT NULL,
    activa             BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_carreras_clave UNIQUE (clave),
    CONSTRAINT ck_carreras_duracion CHECK (duracion_semestres > 0),
    CONSTRAINT ck_carreras_creditos CHECK (creditos_totales > 0)
);

CREATE TABLE materias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave          VARCHAR(20)  NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    creditos       INTEGER      NOT NULL,
    horas_teoria   INTEGER      NOT NULL DEFAULT 0,
    horas_practica INTEGER      NOT NULL DEFAULT 0,
    tipo           VARCHAR(20)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_materias_clave UNIQUE (clave),
    CONSTRAINT ck_materias_tipo CHECK (tipo IN ('OBLIGATORIA', 'OPTATIVA')),
    CONSTRAINT ck_materias_creditos CHECK (creditos >= 0),
    CONSTRAINT ck_materias_horas CHECK (horas_teoria >= 0 AND horas_practica >= 0)
);

CREATE TABLE reticulas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrera_id  BIGINT       NOT NULL REFERENCES carreras (id) ON DELETE RESTRICT,
    clave       VARCHAR(30)  NOT NULL,
    nombre      VARCHAR(150) NOT NULL,
    anio_plan   INTEGER      NOT NULL,
    vigente     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_reticula_carrera_clave UNIQUE (carrera_id, clave)
);
CREATE INDEX idx_reticulas_carrera ON reticulas (carrera_id);

CREATE TABLE reticula_materias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reticula_id BIGINT    NOT NULL REFERENCES reticulas (id) ON DELETE CASCADE,
    materia_id  BIGINT    NOT NULL REFERENCES materias (id)  ON DELETE RESTRICT,
    semestre    INTEGER   NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_reticula_materia UNIQUE (reticula_id, materia_id),
    CONSTRAINT ck_reticula_materias_semestre CHECK (semestre > 0)
);
CREATE INDEX idx_reticula_materias_materia ON reticula_materias (materia_id);

-- Prerrequisitos: auto-relación N:M entre filas de reticula_materias
CREATE TABLE reticula_materia_prerequisitos (
    reticula_materia_id BIGINT NOT NULL REFERENCES reticula_materias (id) ON DELETE CASCADE,
    prerequisito_id     BIGINT NOT NULL REFERENCES reticula_materias (id) ON DELETE RESTRICT,
    PRIMARY KEY (reticula_materia_id, prerequisito_id),
    CONSTRAINT ck_prerequisito_distinto CHECK (reticula_materia_id <> prerequisito_id)
);
CREATE INDEX idx_prerequisitos_prereq ON reticula_materia_prerequisitos (prerequisito_id);

-- El prerrequisito debe ser de la misma retícula y de un semestre anterior.
CREATE FUNCTION fn_validar_prerequisito() RETURNS TRIGGER AS $$
DECLARE
    v_reticula_a BIGINT; v_semestre_a INTEGER;
    v_reticula_b BIGINT; v_semestre_b INTEGER;
BEGIN
    SELECT reticula_id, semestre INTO v_reticula_a, v_semestre_a
      FROM reticula_materias WHERE id = NEW.reticula_materia_id;
    SELECT reticula_id, semestre INTO v_reticula_b, v_semestre_b
      FROM reticula_materias WHERE id = NEW.prerequisito_id;

    IF v_reticula_a <> v_reticula_b THEN
        RAISE EXCEPTION 'El prerrequisito debe pertenecer a la misma retícula';
    END IF;
    IF v_semestre_b >= v_semestre_a THEN
        RAISE EXCEPTION 'El prerrequisito debe ubicarse en un semestre anterior';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validar_prerequisito
    BEFORE INSERT OR UPDATE ON reticula_materia_prerequisitos
    FOR EACH ROW EXECUTE FUNCTION fn_validar_prerequisito();

-- ---------------------------------------------------------------------
-- PERSONAS: alumnos y profesores
