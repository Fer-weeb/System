CREATE TABLE periodos_escolares (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave                    VARCHAR(20)  NOT NULL,
    nombre                   VARCHAR(100) NOT NULL,
    fecha_inicio             DATE         NOT NULL,
    fecha_fin                DATE         NOT NULL,
    fecha_inicio_inscripcion DATE,
    fecha_fin_inscripcion    DATE,
    estatus                  VARCHAR(20)  NOT NULL DEFAULT 'PLANIFICACION',
    created_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_periodos_clave UNIQUE (clave),
    CONSTRAINT ck_periodos_estatus CHECK (estatus IN ('PLANIFICACION', 'ACTIVO', 'CERRADO')),
    CONSTRAINT ck_periodos_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_periodos_fechas_inscripcion CHECK (
        fecha_inicio_inscripcion IS NULL OR fecha_fin_inscripcion IS NULL
        OR fecha_fin_inscripcion >= fecha_inicio_inscripcion)
);
-- A lo más un periodo ACTIVO a la vez
CREATE UNIQUE INDEX uk_periodos_un_activo ON periodos_escolares (estatus) WHERE estatus = 'ACTIVO';

CREATE TABLE grupos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave       VARCHAR(20) NOT NULL,
