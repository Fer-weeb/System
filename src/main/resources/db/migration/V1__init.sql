    updated_at        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_inscripcion_alumno_grupo UNIQUE (alumno_id, grupo_id),
    CONSTRAINT ck_inscripciones_estatus CHECK (estatus IN
        ('INSCRITO', 'BAJA', 'ACREDITADA', 'REPROBADA'))
);
CREATE INDEX idx_inscripciones_grupo_estatus ON inscripciones (grupo_id, estatus);
CREATE INDEX idx_inscripciones_alumno_periodo ON inscripciones (alumno_id, periodo_id);
CREATE INDEX idx_inscripciones_periodo ON inscripciones (periodo_id);

-- inscripciones.periodo_id debe coincidir con grupos.periodo_id
CREATE FUNCTION fn_validar_periodo_inscripcion() RETURNS TRIGGER AS $$
DECLARE
    v_periodo BIGINT;
BEGIN
    SELECT periodo_id INTO v_periodo FROM grupos WHERE id = NEW.grupo_id;
    IF v_periodo IS DISTINCT FROM NEW.periodo_id THEN
        RAISE EXCEPTION 'El periodo de la inscripción no coincide con el periodo del grupo';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validar_periodo_inscripcion
    BEFORE INSERT OR UPDATE OF grupo_id, periodo_id ON inscripciones
    FOR EACH ROW EXECUTE FUNCTION fn_validar_periodo_inscripcion();

CREATE TABLE evaluaciones (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id         BIGINT       NOT NULL REFERENCES grupos (id) ON DELETE CASCADE,
    nombre           VARCHAR(80)  NOT NULL,
    porcentaje       NUMERIC(5,2) NOT NULL,
    orden            INTEGER      NOT NULL,
    fecha_aplicacion DATE,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evaluacion_grupo_orden UNIQUE (grupo_id, orden),
    CONSTRAINT ck_evaluaciones_porcentaje CHECK (porcentaje > 0 AND porcentaje <= 100)
);
CREATE INDEX idx_evaluaciones_grupo ON evaluaciones (grupo_id);

-- Garantiza que la suma de porcentajes por grupo nunca exceda 100
CREATE FUNCTION fn_validar_suma_porcentajes() RETURNS TRIGGER AS $$
DECLARE
    v_suma NUMERIC;
BEGIN
    SELECT COALESCE(SUM(porcentaje), 0) INTO v_suma
      FROM evaluaciones
     WHERE grupo_id = NEW.grupo_id AND id <> COALESCE(NEW.id, -1);
    IF v_suma + NEW.porcentaje > 100 THEN
        RAISE EXCEPTION 'La suma de porcentajes del grupo % excede 100 (actual: %, nuevo: %)',
            NEW.grupo_id, v_suma, NEW.porcentaje;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validar_suma_porcentajes
    BEFORE INSERT OR UPDATE OF porcentaje, grupo_id ON evaluaciones
    FOR EACH ROW EXECUTE FUNCTION fn_validar_suma_porcentajes();

