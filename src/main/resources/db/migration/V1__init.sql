CREATE TABLE alumnos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT REFERENCES usuarios (id) ON DELETE SET NULL,
    matricula        VARCHAR(20)  NOT NULL,
    curp             VARCHAR(18)  NOT NULL,
    nombre           VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100),
    fecha_nacimiento DATE         NOT NULL,
    telefono         VARCHAR(20),
    estatus          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',
    carrera_id       BIGINT       NOT NULL REFERENCES carreras (id)  ON DELETE RESTRICT,
    reticula_id      BIGINT       NOT NULL REFERENCES reticulas (id) ON DELETE RESTRICT,
    semestre_actual  INTEGER      NOT NULL DEFAULT 1,
    fecha_ingreso    DATE         NOT NULL,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_alumnos_matricula UNIQUE (matricula),
    CONSTRAINT uk_alumnos_curp      UNIQUE (curp),
    CONSTRAINT uk_alumnos_usuario   UNIQUE (usuario_id),
    CONSTRAINT ck_alumnos_estatus CHECK (estatus IN
        ('ACTIVO', 'BAJA_TEMPORAL', 'BAJA_DEFINITIVA', 'EGRESADO', 'TITULADO')),
    CONSTRAINT ck_alumnos_curp CHECK (char_length(curp) = 18),
    CONSTRAINT ck_alumnos_semestre CHECK (semestre_actual > 0)
);
CREATE INDEX idx_alumnos_carrera  ON alumnos (carrera_id);
CREATE INDEX idx_alumnos_reticula ON alumnos (reticula_id);
CREATE INDEX idx_alumnos_estatus  ON alumnos (estatus);

