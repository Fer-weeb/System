    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripcion_id BIGINT       NOT NULL REFERENCES inscripciones (id) ON DELETE CASCADE,
    evaluacion_id  BIGINT       NOT NULL REFERENCES evaluaciones (id)  ON DELETE CASCADE,
    nota           NUMERIC(5,2) NOT NULL,
    observaciones  VARCHAR(255),
    registrado_por BIGINT REFERENCES usuarios (id) ON DELETE SET NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_calificacion_inscripcion_evaluacion UNIQUE (inscripcion_id, evaluacion_id),
    CONSTRAINT ck_calificaciones_nota CHECK (nota >= 0 AND nota <= 100)
);
CREATE INDEX idx_calificaciones_evaluacion ON calificaciones (evaluacion_id);

